def _shellcheck_command():
    """shellcheck from this interpreter's environment (shellcheck-py) if installed, else PATH."""
    local = os.path.join(os.path.dirname(sys.executable), "shellcheck")
    return local if os.path.exists(local) else shutil.which("shellcheck")


def _tracked_shell_scripts():
    result = subprocess.run(["git", "ls-files", "*.sh"], cwd=REPO_ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        pytest.skip("not a git checkout")
    # gradlew has no .sh extension and is generated by Gradle, so it is never listed here.
    return result.stdout.split()


def test_shell_scripts_pass_shellcheck():
    shellcheck = _shellcheck_command()
    if shellcheck is None:
        pytest.skip("shellcheck not installed (pip install -r icons/requirements-dev.txt)")
    scripts = _tracked_shell_scripts()
    assert "pick_icon.sh" in scripts

    result = subprocess.run([shellcheck, *scripts], cwd=REPO_ROOT, capture_output=True, text=True)

    assert result.returncode == 0, result.stdout + result.stderr
